// Normalize は勘定科目の入力を標準科目名へ写像する。
// 手順: (1) 半角/全角の空白類をすべて除去 (2) 別名表にあれば標準名へ変換。
// 未知の表記は空白除去後のまま返す (採点側で不一致となる)。
func Normalize(input string) string {
	s := strings.Map(func(r rune) rune {
		if r == ' ' || r == '\t' || r == '　' {
			return -1
		}
		return r
	}, input)
	if canonical, ok := aliases[s]; ok {
		return canonical
	}
	return s
}
